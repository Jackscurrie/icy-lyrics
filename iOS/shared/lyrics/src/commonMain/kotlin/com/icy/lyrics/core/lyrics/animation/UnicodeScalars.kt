package com.icy.lyrics.core.lyrics.animation

/** Surrogate-aware equivalents of the Android renderer's Character operations. */
internal fun String.lyricCodePointAt(offset: Int): Int {
  val first = this[offset]
  val second = getOrNull(offset + 1)
  return if (first.isHighSurrogate() && second != null && second.isLowSurrogate()) {
    0x10000 + ((first.code - 0xD800) shl 10) + second.code - 0xDC00
  } else first.code
}

internal fun Int.lyricCodePointCharCount(): Int = if (this >= 0x10000) 2 else 1

internal fun Int.isInvisibleUnicodeScalar(): Boolean = if (this <= 0xFFFF) {
  val char = toChar()
  char.isWhitespace() || char.category in INVISIBLE_CATEGORIES
} else inRanges(SUPPLEMENTARY_INVISIBLE)

internal fun Int.isDecorationUnicodeScalar(): Boolean = if (this <= 0xFFFF) {
  toChar().category in DECORATION_CATEGORIES
} else inRanges(SUPPLEMENTARY_DECORATION)

private fun Int.inRanges(ranges: IntArray): Boolean {
  var low = 0
  var high = ranges.size / 2 - 1
  while (low <= high) {
    val middle = (low + high) ushr 1
    when {
      this < ranges[middle * 2] -> high = middle - 1
      this > ranges[middle * 2 + 1] -> low = middle + 1
      else -> return true
    }
  }
  return false
}

private val INVISIBLE_CATEGORIES = setOf(
  CharCategory.CONTROL, CharCategory.FORMAT, CharCategory.LINE_SEPARATOR,
  CharCategory.PARAGRAPH_SEPARATOR, CharCategory.SPACE_SEPARATOR,
)
private val DECORATION_CATEGORIES = setOf(
  CharCategory.CONNECTOR_PUNCTUATION, CharCategory.DASH_PUNCTUATION,
  CharCategory.START_PUNCTUATION, CharCategory.END_PUNCTUATION,
  CharCategory.INITIAL_QUOTE_PUNCTUATION, CharCategory.FINAL_QUOTE_PUNCTUATION,
  CharCategory.OTHER_PUNCTUATION, CharCategory.NON_SPACING_MARK,
  CharCategory.COMBINING_SPACING_MARK, CharCategory.ENCLOSING_MARK,
)

