import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const [transformersLicense, nobleLicense] = await Promise.all([
  readFile(resolve(root, "docs/licenses/transformers-js-APACHE-2.0.txt"), "utf8"),
  readFile(resolve(root, "docs/licenses/noble-hashes-MIT.txt"), "utf8"),
]);
const licenseBanner = [
  "/*!",
  "Icy Lyrics Auto-time third-party licenses",
  "Transformers.js by Hugging Face - Apache License 2.0",
  transformersLicense.trimEnd(),
  "",
  "@noble/hashes - MIT License",
  nobleLicense.trimEnd(),
  "*/",
].join("\n");
const result = await build({
  entryPoints: [resolve(root, "src/components/ReactComponents/LyricCreator/autoTiming/worker.ts")],
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: ["chrome120"],
  minify: true,
  legalComments: "inline",
  // The worker is embedded as a string in the extension. Keep the full
  // licenses inside that string so single-file downloads carry them too.
  banner: { js: licenseBanner },
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
    global: "globalThis",
  },
});

const output = result.outputFiles?.[0]?.text;
if (!output) throw new Error("The Auto-time worker build produced no JavaScript.");

const destination = resolve(root, "src/generated/autoTimingWorkerSource.ts");
await mkdir(dirname(destination), { recursive: true });
await writeFile(
  destination,
  `// Generated by scripts/build-auto-timing-worker.mjs. Do not edit.\nexport default ${JSON.stringify(output)};\n`,
  "utf8"
);
console.log(`Generated Auto-time worker (${output.length.toLocaleString()} characters).`);
